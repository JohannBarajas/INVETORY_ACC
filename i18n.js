const dicts = { en, es };
const LOCALES = { en: "en-US", es: "es-US" };

function pick() {
  try { const s = localStorage.getItem("lang"); if (dicts[s]) return s; } catch (_) {}
  const nav = navigator.languages?.length ? navigator.languages : [navigator.language || "en"];
  return nav.some((l) => /^es\b/i.test(l)) ? "es" : "en";
}

export let lang = pick();
export let locale = LOCALES[lang];
document.documentElement.lang = lang;

export function setLang(l) {
  if (!dicts[l]) return;
  lang = l; locale = LOCALES[l];
  document.documentElement.lang = l;
  try { localStorage.setItem("lang", l); } catch (_) {}
}

export function t(k, vars = {}) {
  const v = dicts[lang][k] ?? en[k] ?? k;
  return typeof v === "function" ? v(vars) : v.replace(/\{(\w+)\}/g, (m, n) => (n in vars ? vars[n] : m));
}

