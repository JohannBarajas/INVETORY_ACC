export function errText(e) {
  if (e?.local) return e.message;                  // already written with t()
  const msg = (e?.message || "").replace(/^.*?ERROR:\s*/, "").trim();
  if (!msg) return t("somethingWrong");
  for (const [re, k] of SERVER) { const m = msg.match(re); if (m) return t(k, { n: m[1] }); }
  return lang === "en" ? msg : t("e_other", { msg });
}

/* Prices typed with a comma (19,99) are read as 19.99. Empty → NaN. */
export function dec(v) {
  const s = String(v ?? "").trim().replace(/\s/g, "").replace(",", ".");
  return s === "" || !/^\d*\.?\d*$/.test(s) ? NaN : parseFloat(s);
}
